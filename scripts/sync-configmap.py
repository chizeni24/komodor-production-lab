#!/usr/bin/env python3
"""Regenerate k8s/api-configmap.yaml from app.py and stamp the code checksum on the API pod template.

The checksum annotation makes a code change roll the Deployment when the manifests are applied,
so the cluster never keeps running stale code from an old ConfigMap.
"""
import hashlib
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]


def checksum(source):
    return hashlib.sha256(source.encode()).hexdigest()[:16]


def render_configmap(source):
    body = "".join(("    " + line) if line.strip() else "\n" for line in source.splitlines(True))
    return ("# Generated by scripts/sync-configmap.py from app.py. Do not edit by hand.\n"
            "apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: kaop-api-code\n  namespace: kaop-demo\n"
            "data:\n  app.py: |\n" + body)


def main(check_only=False):
    source = (ROOT / "app.py").read_text()
    configmap = render_configmap(source)
    api_path = ROOT / "k8s/api.yaml"
    api = api_path.read_text()
    updated = re.sub(r'(kaop-demo/code-checksum: )"[0-9a-f]*"', r'\1"' + checksum(source) + '"', api)
    current_cm = (ROOT / "k8s/api-configmap.yaml").read_text() if (ROOT / "k8s/api-configmap.yaml").exists() else ""
    if check_only:
        if current_cm != configmap or updated != api:
            print("FAIL: ConfigMap or checksum is stale; run scripts/sync-configmap.py", file=sys.stderr)
            return 1
        print("PASS: ConfigMap and code checksum match app.py")
        return 0
    (ROOT / "k8s/api-configmap.yaml").write_text(configmap)
    api_path.write_text(updated)
    print("Updated k8s/api-configmap.yaml and the code checksum in k8s/api.yaml")
    return 0


if __name__ == "__main__":
    sys.exit(main(check_only="--check" in sys.argv))
